"""Turn a list of run results into console tables and a Markdown report."""

from __future__ import annotations

from collections import defaultdict

from smartdialer.sim.scenarios import SCENARIOS

MODES = ("PROGRESSIVE", "PREDICTIVE")


def pct(x: float, digits: int = 1) -> str:
    return f"{100 * x:.{digits}f}%"


def _row(r: dict) -> list[str]:
    u, c, s = r["utilization"], r["calls"], r["safety"]["decisions"]
    decisions = " / ".join(str(s.get(k, 0)) for k in ("APPROVE", "REDUCE", "REJECT", "FALLBACK_PROGRESSIVE"))
    return [r["provider"], r["mode"].title(), pct(u["connected"]), pct(u["connected_steady"]), pct(u["waiting"]),
            pct(u["wrap_up"]), str(c["initiated"]), str(c["answered"]), str(c["connected"]),
            f"{c['abandoned']} ({pct(c['abandon_rate'], 2)})", f"{c['hung_up_excess']} ({c['hung_up_but_answered']})", decisions]


HEADER = ["Prov", "Mode", "Util", "Util (>3 min)", "Waiting", "Wrap-up", "Initiated", "Answered", "Connected",
          "Abandons (rate)", "Hung up (dead air)", "Decisions A/R/X/F"]


def _table(rows: list[list[str]], header: list[str]) -> str:
    widths = [max(len(header[i]), *(len(r[i]) for r in rows)) for i in range(len(header))]
    line = lambda cells: "| " + " | ".join(c.ljust(w) for c, w in zip(cells, widths)) + " |"
    return "\n".join([line(header), "|" + "|".join("-" * (w + 2) for w in widths) + "|", *map(line, rows)])


def _group(results: list[dict]) -> dict:
    by = defaultdict(list)
    for r in results:
        by[r["scenario"]].append(r)
    return by


def uplift_lines(runs: list[dict]) -> list[str]:
    out = []
    for prov in sorted({r["provider"] for r in runs}):
        pair = {r["mode"]: r for r in runs if r["provider"] == prov}
        if len(pair) == 2:
            a, b = pair["PROGRESSIVE"], pair["PREDICTIVE"]
            du = b["utilization"]["connected_steady"] - a["utilization"]["connected_steady"]
            rel = b["utilization"]["connected_steady"] / max(1e-9, a["utilization"]["connected_steady"]) - 1
            out.append(f"- Provider {prov}: steady-state utilisation {pct(a['utilization']['connected_steady'])} -> "
                       f"{pct(b['utilization']['connected_steady'])} ({du * 100:+.1f} pts, {rel * 100:+.0f}% relative); "
                       f"connected calls {a['calls']['connected']} -> {b['calls']['connected']}; abandons "
                       f"{a['calls']['abandoned']} -> {b['calls']['abandoned']} "
                       f"(peak rolling rate {pct(b['safety']['peak_rolling_abandon_rate'], 2)}).")
    return out


def console(results: list[dict]) -> str:
    parts = []
    for key, runs in _group(results).items():
        sc = SCENARIOS[key]
        parts.append(f"\nScenario {key}: {sc.name}  ({sc.description})\n")
        parts.append(_table([_row(r) for r in sorted(runs, key=lambda r: (r["provider"], r["mode"]))], HEADER))
        parts.extend(["", *uplift_lines(runs)])
    return "\n".join(parts)


def markdown(results: list[dict]) -> str:
    first = results[0]
    md = [
        "# Simulation results",
        "",
        f"Generated by `python -m smartdialer.sim`. {first['agents']} agents unless noted, seed {first['seed']}, "
        "virtual time (no sleeping), real PostgreSQL, mock providers A and B. Every number below comes from the "
        "database after the run; nothing is estimated.",
        "",
        "**Columns.** *Util* = share of online agent-seconds spent CONNECTED to a borrower (the number that "
        "predictive dialing exists to raise). *Util (>3 min)* excludes the first three minutes, when predictive is "
        "still gathering evidence and behaves like progressive. *Waiting* = AVAILABLE + RESERVED + DIALING (an agent "
        "idle or listening to ringing). *Initiated / Answered / Connected* are calls. *Abandons* are answered calls "
        "with no agent free, as a share of answered. *Hung up* = still-ringing calls cancelled by the Safety "
        "Controller (not abandons). *Decisions* = Safety Controller verdict counts: Approve / Reduce / Reject / "
        "Fallback-to-progressive.",
        "",
    ]
    for key, runs in _group(results).items():
        sc = SCENARIOS[key]
        md += [f"## Scenario {key}: {sc.name}", "", sc.description, ""]
        md.append(_table([_row(r) for r in sorted(runs, key=lambda r: (r["provider"], r["mode"]))], HEADER))
        md += ["", "**Predictive vs progressive**", "", *uplift_lines(runs), ""]
        for r in sorted(runs, key=lambda r: (r["provider"], r["mode"])):
            if r["mode"] != "PREDICTIVE":
                continue
            p, s, d = r["pacing"], r["safety"], r["dialer"]
            fb = s["fallback_reasons"]
            incidents = r["provider_incidents"]
            ps = incidents["stats"]
            md += [
                f"<details><summary>Provider {r['provider']} predictive: pacing, safety and provider detail</summary>",
                "",
                f"- Pacing: avg proposed {p['avg_proposed']:.1f}, avg approved {p['avg_approved']:.1f} per tick; "
                f"avg / max agentless calls ringing {p['avg_ringing_agentless']:.1f} / {p['max_ringing_agentless']}; "
                f"first predictive permit at {p['first_predictive_second']}s.",
                f"- Fallback triggers (ticks; one tick can have several): breaker {fb['circuit']}, "
                f"answer-rate shock {fb['shock']}, abandon budget {fb['abandon_budget']}.",
                f"- Late-bound answers {d['late_bound']}, abandons {d['abandons_counted']}, excess hang-ups {d['hung_up_excess']}.",
                f"- Provider: {ps['place_attempts']} place attempts, {ps['errors']} errors, {ps['timeouts']} timeouts "
                f"({ps['timeouts_but_placed']} of them actually placed), {ps['event_copies_sent'] - ps['events_emitted']} duplicate "
                f"events, {ps['events_dropped_in_outage']} events lost in outages; breaker transitions "
                f"{incidents['breaker_transitions'] or 'none'}.",
                f"- Reconciler: {incidents['reconciler']['passes']} passes, examined {incidents['reconciler']['examined']}, "
                f"brought up to date {incidents['reconciler']['brought_up_to_date']}, not found {incidents['reconciler']['not_found']}, "
                f"unreachable {incidents['reconciler']['unreachable']}.",
                "", "</details>", "",
            ]
    return "\n".join(md)
